import { chromium } from "playwright-core";
import { Keypair } from "@solana/web3.js";
import bs58 from "bs58";
const kp = Keypair.generate();
await fetch("http://127.0.0.1:8899", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "surfnet_setAccount", params: [kp.publicKey.toBase58(), { lamports: 5e9 }] }) });
const b = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 }, colorScheme: "dark" });
await ctx.route("**/api/vanity**", (r) => r.abort());
await ctx.addInitScript((s) => { if (!localStorage.getItem("burner:v1")) localStorage.setItem("burner:v1", s); }, bs58.encode(kp.secretKey));
const page = await ctx.newPage();
const logs: string[] = [];
page.on("console", (m) => { if (["error", "warning"].includes(m.type())) logs.push(`${m.type()}: ${m.text().slice(0, 200)}`); });
page.on("request", (r) => { if (/swap\/solana|\/api\/legs|sendTransaction/.test(r.url() + (r.postData() ?? ""))) logs.push(`req ${r.method()} ${r.url().slice(0, 90)} ${(r.postData() ?? "").match(/"method":"(\w+)"/)?.[1] ?? ""}`); });
await page.goto("http://localhost:5180/swap", { waitUntil: "domcontentloaded" }); await page.waitForTimeout(3000);
await page.locator("button", { hasText: "A throwaway wallet" }).first().click(); await page.waitForTimeout(2500);
await page.locator("button", { hasText: /start aping/i }).first().click().catch(() => {}); await page.waitForTimeout(3000);
console.log("header:", (await page.locator(".nav").first().innerText()).replace(/\s+/g, " ").slice(-60));
await page.getByLabel("You pay").fill("0.1"); await page.waitForTimeout(6000);
for (let i = 0; i < 30 && !(await page.locator("button.swap-go").isEnabled()); i++) await page.waitForTimeout(1000);
console.log("swap btn enabled:", await page.locator("button.swap-go").isEnabled(), "| errs:", await page.locator(".swap-err").allInnerTexts(), "| receive:", await page.locator(".swap-row").nth(1).innerText().catch(() => "?"));
await page.locator("button.swap-go").click(); await page.waitForTimeout(70000);
console.log("errs:", await page.locator(".swap-err").allInnerTexts());
console.log("step:", await page.locator(".swap-step").allInnerTexts().catch(() => []));
console.log("rows:", await page.locator("ol.swap-status li").evaluateAll((els) => els.map((e) => `${e.getAttribute("data-s")} ${e.textContent?.replace(/\s+/g, " ").slice(0, 120)}`)));
console.log("toasts:", await page.locator(".toast").allInnerTexts());
console.log(logs.slice(0, 25).join("\n"));
await b.close();
